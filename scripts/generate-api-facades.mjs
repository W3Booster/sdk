import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const modules = [
  { name: 'game-data', contract: 'game-data-contracts.d.ts', runtime: 'game-data.runtime.js' },
  { name: 'index', contract: 'contracts.ts', runtime: 'index.runtime.js', version: true },
  { name: 'selectors', contract: 'selectors-contracts.d.ts', runtime: 'selectors.runtime.js' },
  { name: 'store', contract: 'store-contracts.d.ts', runtime: 'store.runtime.js' },
  { name: 'app', contract: 'app-contracts.d.ts', runtime: 'app.runtime.js' },
  { name: 'standard-game', contract: 'standard-game-contracts.d.ts', runtime: 'standard-game.runtime.js' },
  { name: 'assets', contract: 'assets-contracts.d.ts', runtime: 'assets.runtime.js' }
];

const stale = [];
for (const module of modules) {
  const contractPath = resolve(root, 'api-source', module.contract);
  const contractSource = await readFile(contractPath, 'utf8');
  const expected = generateFacade(module, contractSource);
  const target = resolve(root, 'api-source', `${module.name}.ts`);
  if (checkOnly) {
    const actual = await readFile(target, 'utf8').catch(() => '');
    if (actual !== expected) stale.push(`${module.name}.ts`);
  } else {
    await writeFile(target, expected);
  }
}

if (stale.length) {
  throw new Error(`Generated API facade sources are stale: ${stale.join(', ')}. Run npm run build:api.`);
}

function generateFacade(module, contractSource) {
  const contractBase = module.contract.replace(/(?:\.d)?\.ts$/, '');
  const source = ts.createSourceFile(module.contract, contractSource, ts.ScriptTarget.Latest, true);
  const values = exportedValues(source, contractSource);
  const lines = [
    '// Generated from the public contract by scripts/generate-api-facades.mjs.',
    '// Do not edit this file directly.',
    '// @ts-expect-error The runtime intentionally has no hand-maintained declaration file.',
    `import * as runtime from './${module.runtime}';`,
    `import type * as Contract from './${contractBase}.js';`,
    '',
    `export type * from './${contractBase}.js';`
  ];
  if (module.version) {
    lines.push(`export { SDK_VERSION, PROTOCOL_VERSION, SUPPORTED_PROTOCOL_VERSIONS } from './version.js';`);
  }
  lines.push('');
  for (const value of values) {
    if (value.typeAlias) lines.push(value.typeAlias);
  }
  if (values.some(value => value.typeAlias)) lines.push('');
  for (const value of values) {
    if (value.documentation) lines.push(value.documentation);
    lines.push(`export const ${value.name}: typeof Contract.${value.name} = runtime.${value.name};`);
  }
  return `${lines.join('\n')}\n`;
}

function exportedValues(source, text) {
  const result = [];
  const names = new Set();
  const typeDeclarations = new Map();
  for (const statement of source.statements) {
    if (!statement.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) continue;
    if ((ts.isInterfaceDeclaration(statement) || ts.isTypeAliasDeclaration(statement) || ts.isClassDeclaration(statement)) && statement.name) {
      typeDeclarations.set(statement.name.text, statement);
    }
  }
  for (const statement of source.statements) {
    if (!statement.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) continue;
    const candidates = [];
    if ((ts.isFunctionDeclaration(statement) || ts.isClassDeclaration(statement) || ts.isEnumDeclaration(statement)) && statement.name) {
      candidates.push(statement.name.text);
    } else if (ts.isVariableStatement(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (ts.isIdentifier(declaration.name)) candidates.push(declaration.name.text);
      }
    }
    for (const name of candidates) {
      if (names.has(name)) continue;
      names.add(name);
      const documentation = statement.jsDoc?.map(block => text.slice(block.pos, block.end).trim()).join('\n') ?? '';
      const typeDeclaration = typeDeclarations.get(name);
      const parameterNames = new Set(typeDeclaration?.typeParameters?.map(parameter => parameter.name.text) ?? []);
      const parameters = typeDeclaration?.typeParameters?.length
        ? `<${typeDeclaration.typeParameters.map(parameter => qualifyContractTypes(
          parameter.getText(source), typeDeclarations.keys(), parameterNames
        )).join(', ')}>`
        : '';
      const argumentsList = typeDeclaration?.typeParameters?.length
        ? `<${typeDeclaration.typeParameters.map(parameter => parameter.name.text).join(', ')}>`
        : '';
      const typeAlias = typeDeclaration
        ? `export type ${name}${parameters} = Contract.${name}${argumentsList};`
        : '';
      result.push({ name, documentation, typeAlias });
    }
  }
  return result;
}

function qualifyContractTypes(value, typeNames, excludedNames) {
  let result = value;
  for (const name of [...typeNames].sort((left, right) => right.length - left.length)) {
    if (excludedNames.has(name)) continue;
    result = result.replace(new RegExp(`(?<![\\w.])${name}(?![\\w])`, 'g'), `Contract.${name}`);
  }
  return result;
}
